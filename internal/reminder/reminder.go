func MessageForLevel(severity string, level int, filename string) string {
	order := []string{"ignore", "gentle", "normal", "passive", "aggressive", "maximum"}
	idx := 1
	switch severity {
	case "ignore":
		idx = 0
	case "gentle":
		idx = 1
	case "normal":
		idx = 2
	case "passive":
		idx = 3
	case "aggressive":
		idx = 4
	case "maximum":
		idx = 5
	}
	if level > idx {
		idx = level
	}
	if idx > 5 {
		idx = 5
	}
	arr := messages[order[idx]]
	if len(arr) == 0 {
		arr = messages["normal"]
	}
	msg := arr[rng.Intn(len(arr))]
	return strings.TrimSpace(fmt.Sprintf("%s\n\nFILE: %s", msg, filename))
}
